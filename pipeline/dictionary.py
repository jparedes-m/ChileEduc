"""Step 4: write a data dictionary per dataset, docs/dictionary/<dataset>.md.

Part 1 describes the clean variables: type, published names, years with data,
share of non-missing values and range. Part 2 lists every published column and
the years it appears in, which shows what the mapping file is still missing.
Descriptions come from the optional "description" column of the mapping file;
the PDFs copied to docs/<dataset>/ by the extraction step are the source for them.
"""

import logging
from pathlib import Path

import polars as pl

from pipeline.unification import mapped_names, raw_coverage, read_mapping

log = logging.getLogger(__name__)


def year_ranges(years: list[int]) -> str:
    """[2002, 2003, 2004, 2011] -> '2002-2004, 2011'."""
    years = sorted(years)
    ranges, start = [], None
    for i, y in enumerate(years):
        start = y if start is None else start
        if i + 1 == len(years) or years[i + 1] != y + 1:
            ranges.append(str(start) if start == y else f"{start}-{y}")
            start = None
    return ", ".join(ranges)


def cell(value) -> str:
    return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")


def table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]


def clean_variables(files: list[Path], mapping: pl.DataFrame) -> list[list]:
    lf = pl.scan_parquet(files)
    schema = lf.collect_schema()
    columns = [c for c in schema.names() if c != "year"]
    counts = (
        lf.group_by("year")
        .agg(pl.len().alias("__rows"), *[pl.col(c).is_not_null().sum() for c in columns])
        .sort("year")
        .collect(engine="streaming")
    )
    numeric = [c for c in columns if schema[c].is_numeric()]
    ranges = lf.select(
        *[pl.col(c).min().alias(f"{c}__min") for c in numeric],
        *[pl.col(c).max().alias(f"{c}__max") for c in numeric],
    ).collect(engine="streaming").row(0, named=True) if numeric else {}

    descriptions = {}
    if "description" in mapping.columns:
        descriptions = {d.strip().lower(): t for d, t in mapping.select("desired_names", "description").iter_rows() if d}
    # Mapped variables list their published names; extras were published under their own name.
    sources = {c: [] for c in mapping["desired_names"].drop_nulls().str.strip_chars().str.to_lowercase()}
    for original, desired in mapped_names(mapping).items():
        sources[desired].append(original)

    total = counts["__rows"].sum()
    rows = [["year", str(schema["year"]), "", "", year_ranges(counts["year"].to_list()), "100.0", ""]]
    for c in columns:
        years = counts.filter(pl.col(c) > 0)["year"].to_list()
        span = f"{ranges[f'{c}__min']} to {ranges[f'{c}__max']}" if c in numeric else ""
        rows.append([
            c, str(schema[c]), descriptions.get(c), ", ".join(sorted(sources.get(c, [c.upper()]))),
            year_ranges(years), f"{100 * counts[c].sum() / total:.1f}", span,
        ])
    return rows


def run(datasets: dict, intermediate_dir: Path, clean_dir: Path, mapping_file: Path, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for dataset in datasets:
        files = sorted((clean_dir / dataset).glob("*.parquet"))
        if not files:
            log.warning("[%s] no clean files, dictionary skipped", dataset)
            continue
        mapping = read_mapping(mapping_file, dataset)
        rows_per_year = pl.scan_parquet(files).group_by("year").len().sort("year").collect(engine="streaming")

        coverage = raw_coverage(intermediate_dir / dataset)
        used = mapped_names(mapping)
        clean_names = set(pl.scan_parquet(files).collect_schema().names())
        published = sorted({n for names in coverage.values() for n in names})
        inventory = [
            [n, year_ranges([y for y, names in coverage.items() if n in names]),
             sum(n in names for names in coverage.values()),
             used.get(n) or (n.lower() if n.lower() in clean_names else "not kept")]
            for n in published
        ]
        inventory.sort(key=lambda r: (-r[2], r[0]))

        lines = [
            f"# {dataset.capitalize()} data dictionary",
            "",
            "Generated by `python masterfile.py --steps dictionary`; do not edit by hand.",
            "Descriptions come from the `description` column of the mapping file.",
            "",
            f"{rows_per_year['len'].sum():,} rows in {rows_per_year.height} years.",
            "",
            "## Variables",
            "",
            *table(["variable", "type", "description", "published as", "years with data", "% non-missing", "range"],
                   clean_variables(files, mapping)),
            "",
            "## Rows per year",
            "",
            *table(["year", "rows"], [[y, f"{n:,}"] for y, n in rows_per_year.iter_rows()]),
            "",
            "## Published columns",
            "",
            f"Every column in the MINEDUC files, by number of years it appears in ({len(coverage)} years in total).",
            "",
            *table(["published name", "years", "n years", "clean variable"], inventory),
            "",
        ]
        target = out_dir / f"{dataset}.md"
        target.write_text("\n".join(lines), encoding="utf-8")
        log.info("[%s] dictionary written to %s", dataset, target)
